#!/usr/bin/env perl
use warnings;
use strict;
#Shujun Ou (oushujun@iastate.edu) 
#v0.1 08/10/2019
#v0.2 03/05/2026 Add maxdiv and mincov
#v0.3 07/27/2026 Accept - and ? in class names (hAT-Ac, CMC-Chapaev-3, SINE?)
#v0.4 11/08/2026 Also report the subclass level (LTR, LINE, SINE, TIR, Helitron, ...)

my $usage = "\nCount all-versus-all misclassifications using the cleanup_nested.pl .stat file
	perl count_nested.pl -in sequence.fa.stat -cat [redun|nested|all] [options] > sequence.fa.stat.sum
		-maxdiv	[int]	Maximum divergence (100-identity) to include. Default: 100 (no filter)
		-mincov	[float]	Minimum reciprocal coverage for redun category. Default: 0.95
	Prints two confusion matrices: the class names as annotated (superfamily level; MITE and TIR count as DNA),
	then the subclass level (Helitron; TIR for the other DNA names; else the part before the /: LTR, LINE, SINE...).
\n";

my $input = ''; #input file .stat generated by cleanup_nested.pl
my $cat = "all"; #all: all input entries; redun: only redundant entries (Discarded types); nested: only nested entries (Cleaned types)
my $maxdiv = 100; #max divergence (100 - identity); 100 = no filter
my $mincov = 0.95; #min reciprocal coverage for redun; 0 = no filter

my $k=0;
foreach (@ARGV){
	$input = $ARGV[$k+1] if /^-in$/i and $ARGV[$k+1] !~ /^-/;
	$cat = lc $ARGV[$k+1] if /^-cat$/i and $ARGV[$k+1] !~ /^-/;
	$maxdiv = $ARGV[$k+1] if /^-maxdiv$/i and $ARGV[$k+1] !~ /^-/;
	$mincov = $ARGV[$k+1] if /^-mincov$/i and $ARGV[$k+1] !~ /^-/;
	$k++;
	}

die $usage unless $cat =~ /all|nested|redun/;
open IN, "<$input" or die $usage;

my (%stat, %types, %stat_sub, %types_sub); # pairs by row (modified) and column (modifier) class; events per class
while (<IN>){
	s/\.$//;
	# Skip corrupted rows from multithreading (valid rows have at least 10 fields)
	my @fields = split;
	next if scalar(@fields) < 10;
	next if (/Discarded/ and $cat eq "nested");
	next if (/Cleaned/ and $cat eq "redun");

	# Divergence filter
	my $identity = 0;
	$identity = $1 if /identity:\s+([\d.]+)/;
	next if $identity !~ /^\d+\.?\d*$/; # skip corrupted identity values
	next if $identity > 0 and (100 - $identity) > $maxdiv;

	# Reciprocal coverage filter (redun only)
	if ($cat eq "redun" and $mincov > 0) {
		my ($qcov, $scov) = (0, 0);
		$qcov = $1 if /qcov:\s+([\d.]+)/;
		$scov = $1 if /scov:\s+([\d.]+)/;
		next if $qcov !~ /^\d+\.?\d*$/ or $scov !~ /^\d+\.?\d*$/; # skip corrupted values
		# Only apply filter if both fields are present (backward compat with old .stat files)
		next if ($qcov > 0 and $scov > 0) and ($qcov < $mincov or $scov < $mincov);
	}

	s/MITE/DNA/gi;
	s/TIR/DNA/gi;
	# Class names may contain - and ?, e.g. DNA/hAT-Ac, DNA/CMC-Chapaev-3, SINE?. Excluding
	# them did not merely truncate the name: $type1 must be followed immediately by \s+, so
	# "|LINE/Rex-Babar\t" captured "LINE/Rex", failed on "-Babar", and the whole line was
	# dropped from the matrix. That silently discarded up to 45% of the lines in a
	# RepeatMasker-2.0.8 .stat (Dfam/RepBase names are heavily hyphenated) while leaving an
	# LTR-only library, whose names have no hyphens, essentially untouched -- so the two were
	# not being counted on comparable samples. The - is last in the class so it stays literal.
	my ($type1, $type2) = ($1, $2) if /[\||#]([0-9a-z\/_?-]+)\s+.*[\||#]([0-9a-z\/_?-]+)(;|\s+)/i;
	next unless defined $type1 and defined $type2;
	# Skip truncated type names from corrupted lines (valid types have >=2 chars after /)
	next if ($type1 =~ /\// and $type1 !~ /\/.{2,}/) or ($type2 =~ /\// and $type2 !~ /\/.{2,}/);
	$types{$type1}++;
	$types{$type2}++;
	$stat{$type1}{$type2}++;
	my ($sub1, $sub2) = (&subclass($type1), &subclass($type2));
	$types_sub{$sub1}++;
	$types_sub{$sub2}++;
	$stat_sub{$sub1}{$sub2}++;
	}
close IN;

&print_matrix("superfamily", \%stat, \%types);
print "\n";
&print_matrix("subclass", \%stat_sub, \%types_sub);

# The subclass of a class name: Helitron for any helitron name; TIR for the other DNA names (MITE and TIR were
# renamed DNA above; DNAauto, DNAnona); else the part before the / (LTR, LINE, SINE, nonLTR, rDNA...), as EDTA's
# TEanno.sum groups them. A trailing ? is dropped (SINE?, DNA?/hAT).
sub subclass {
	my $type = shift;
	return 'Helitron' if $type =~ /helitron/i;
	(my $sub = $type) =~ s/\/.*//;
	$sub =~ s/\?$//;
	return $sub =~ /^DNA(auto|nona)?$/i ? 'TIR' : $sub;
}

# Print one confusion matrix: rows are the classes of the modified entries, columns those of the entries that
# modified them, and Inconsistent_rate is the share of a row's pairs whose classes differ. Single-event
# classes are left out.
sub print_matrix {
	my ($level, $stat, $count) = @_;
	print "Confusion matrix of $input for the $cat category at the $level level (maxdiv: $maxdiv)\n";
	my @types = sort {$a cmp $b} grep { $count->{$_} > 1 } keys %$count;

	# Compute column widths for aligned output
	my $col0_w = 0;
	for my $t (@types) {
		$col0_w = length($t) if length($t) > $col0_w;
	}

	my @col_w;
	for my $i (0..$#types) {
		$col_w[$i] = length($types[$i]);
		for my $type1 (@types) {
			my $vw = length($stat->{$type1}{$types[$i]} // 0);
			$col_w[$i] = $vw if $vw > $col_w[$i];
		}
	}

	my $rate_label = "Inconsistent_rate";
	my $rate_w = length($rate_label);

	# Print header
	printf "%-*s", $col0_w, "";
	for my $i (0..$#types) {
		printf "  %*s", $col_w[$i], $types[$i];
	}
	printf "  %*s\n", $rate_w, $rate_label;

	# Print rows
	foreach my $type1 (@types) {
		printf "%-*s", $col0_w, $type1;
		my $true = $stat->{$type1}{$type1} // 0;
		my $all = 0;
		for my $i (0..$#types) {
			my $n = $stat->{$type1}{$types[$i]} // 0;
			$all += $n;
			printf "  %*d", $col_w[$i], $n;
		}
		my $Misclas_rate = 0;
		$Misclas_rate = sprintf("%.4f", ($all-$true)/$all) if $all > 0;
		printf "  %*s\n", $rate_w, $Misclas_rate;
	}
}

